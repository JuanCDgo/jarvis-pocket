function runExecFile(cmd, args, timeoutMs = 15000) {
  return new Promise((resolve) => {
    execFile(cmd, args, { timeout: timeoutMs, maxBuffer: 2 * 1024 * 1024, windowsHide: true }, (err, stdout, stderr) => {
      resolve({
        ok: !err,
        stdout: String(stdout || '').trim(),
        stderr: String(stderr || '').trim(),
        exitCode: err && typeof err.code === 'number' ? err.code : err ? 1 : 0,
      });
    });
  });
}

function sendJson(res, status, data) {
  const body = JSON.stringify(data);
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'Authorization, Content-Type',
    'Access-Control-Allow-Methods': 'GET, POST, DELETE, OPTIONS',
  });
  res.end(body);
}

function isAuthorized(req) {
  const auth = req.headers.authorization || '';
  if (!auth.startsWith('Bearer ')) return false;
  const provided = auth.slice(7).trim();
  const expected = config.token || '';
  if (!provided || !expected || provided.length !== expected.length) return false;
  return crypto.timingSafeEqual(Buffer.from(provided), Buffer.from(expected));
}

function readJsonBody(req, limitBytes = 1024 * 1024) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let total = 0;
    req.on('data', (chunk) => {
      total += chunk.length;
      if (total > limitBytes) {
        reject(new Error('Payload too large'));
        req.destroy();
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => {
      try {
        const text = Buffer.concat(chunks).toString('utf-8');
        resolve(text ? JSON.parse(text) : {});
      } catch {
        reject(new Error('Invalid JSON'));
      }
    });
    req.on('error', reject);
  });
}

function getRootDir(dirKey) {
  return dirKey === 'downloads' ? config.downloadsDir : config.dropDir;
}

function safeResolveFile(rootDir, filename) {
  const cleanName = path.basename(String(filename || '')).replace(/[<>:"/\\|?*\x00-\x1f]/g, '_');
  if (!cleanName || cleanName === '.' || cleanName === '..') return null;
  const full = path.resolve(rootDir, cleanName);
  const rel = path.relative(rootDir, full);
  if (rel.startsWith('..') || path.isAbsolute(rel)) return null;
  return { full, cleanName };
}

function isValidHttpUrl(value) {
  try {
    const u = new URL(String(value || ''));
    return u.protocol === 'http:' || u.protocol === 'https:';
  } catch {
    return false;
  }
}

async function getDiskInfo() {
  if (process.platform !== 'win32') return [];
  const ps =
    'Get-CimInstance Win32_LogicalDisk -Filter "DriveType=3" | Select-Object DeviceID,VolumeName,Size,FreeSpace | ConvertTo-Json -Compress';
  const res = await runExecFile('powershell.exe', ['-NoProfile', '-Command', ps], 8000);
  if (!res.ok || !res.stdout) return [];
  try {
    const parsed = JSON.parse(res.stdout);
    const list = Array.isArray(parsed) ? parsed : [parsed];
    return list.map((d) => ({
      drive: d.DeviceID,
      label: d.VolumeName || 'Disco Local',
      totalBytes: Number(d.Size) || 0,
      freeBytes: Number(d.FreeSpace) || 0,
      usedBytes: Math.max(0, (Number(d.Size) || 0) - (Number(d.FreeSpace) || 0)),
    }));
  } catch {
    return [];
  }
}

async function checkBinary(name) {
  const cmd = process.platform === 'win32' ? 'where.exe' : 'which';
  const res = await runExecFile(cmd, [name], 3000);
  return res.ok && Boolean(res.stdout);
}

async function captureScreenshot() {
  if (process.platform !== 'win32') {
    throw new Error('Captura de pantalla soportada solo en Windows.');
  }
  const tmpFile = path.join(os.tmpdir(), `jarvis-shot-${Date.now()}.png`);
  const ps = `
Add-Type -AssemblyName System.Windows.Forms
Add-Type -AssemblyName System.Drawing
$bounds = [System.Windows.Forms.Screen]::PrimaryScreen.Bounds
$bmp = New-Object System.Drawing.Bitmap($bounds.Width, $bounds.Height)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.CopyFromScreen($bounds.Location, [System.Drawing.Point]::Empty, $bounds.Size)
$bmp.Save('${tmpFile.replace(/'/g, "''")}', [System.Drawing.Imaging.ImageFormat]::Png)
$g.Dispose()
$bmp.Dispose()
`;
  const res = await runExecFile('powershell.exe', ['-NoProfile', '-Command', ps], 10000);
  if (!res.ok || !fs.existsSync(tmpFile)) {
    throw new Error(res.stderr || 'No se pudo capturar la pantalla');
  }
  const buf = fs.readFileSync(tmpFile);
  fs.unlinkSync(tmpFile);
  return buf;
}

function startDownloadJob({ url, mode, quality, engine, cobaltUrl }) {
  const job = {
    id: crypto.randomUUID(),
    url,
    mode: mode === 'audio' ? 'audio' : 'video',
    quality: quality || '1080',
    engine: engine || 'yt-dlp',
    status: 'running',
    progress: 'Iniciando descarga...',
    outputFile: null,
    createdAt: new Date().toISOString(),
  };
  downloadJobs.unshift(job);
  if (downloadJobs.length > 50) downloadJobs.length = 50;

  if (job.engine === 'cobalt' && (cobaltUrl || config.cobaltApiUrl)) {
    const endpoint = (cobaltUrl || config.cobaltApiUrl).replace(/\/+$/, '');
    fetch(endpoint, {
      method: 'POST',
      headers: { Accept: 'application/json', 'Content-Type': 'application/json' },
      body: JSON.stringify({
        url,
        downloadMode: job.mode === 'audio' ? 'audio' : 'auto',
        videoQuality: job.quality,
      }),
    })
      .then((r) => r.json())
      .then((data) => {
        if (data?.url) {
          job.status = 'completed';
          job.progress = 'Listo vía Cobalt';
          job.outputFile = data.filename || data.url;
        } else {
          job.status = 'failed';
          job.progress = data?.error?.code || 'Cobalt no devolvió URL de descarga';
        }
      })
      .catch((err) => {
        job.status = 'failed';
        job.progress = `Error Cobalt: ${err.message}`;
      });
    return job;
  }

  // Native yt-dlp download to JarvisDownloads
  const outTemplate = path.join(config.downloadsDir, '%(title).80s [%(id)s].%(ext)s');
  const args =
    job.mode === 'audio'
      ? ['-x', '--audio-format', 'mp3', '-o', outTemplate, '--newline', url]
      : [
          '-f',
          job.quality === '720'
            ? 'bestvideo[height<=720]+bestaudio/best[height<=720]/best'
            : job.quality === '1080'
              ? 'bestvideo[height<=1080]+bestaudio/best[height<=1080]/best'
              : 'bestvideo+bestaudio/best',
          '--merge-output-format',
          'mp4',
          '-o',
          outTemplate,
          '--newline',
          url,
        ];

  const child = spawn('yt-dlp', args, { windowsHide: true });
  child.on('error', () => {
    job.status = 'failed';
    job.progress = 'yt-dlp no está instalado en PATH. Instalalo con: winget install yt-dlp.yt-dlp';
  });
  child.stdout.on('data', (chunk) => {
    const line = String(chunk).trim().split(/\r?\n/).pop();
    if (line) job.progress = line.slice(0, 140);
  });
  child.stderr.on('data', (chunk) => {
    const line = String(chunk).trim().split(/\r?\n/).pop();
    if (line && job.status === 'running') job.progress = line.slice(0, 140);
  });
  child.on('close', (code) => {
    if (job.status === 'failed') return;
    if (code === 0) {
      job.status = 'completed';
      job.progress = `Guardado en ${config.downloadsDir}`;
    } else {
      job.status = 'failed';
      job.progress = `yt-dlp finalizó con código ${code}`;
    }
  });

  return job;
}

function serveStaticDist(req, res, pathname) {
  const distDir = path.join(ROOT, 'dist');
  if (!fs.existsSync(distDir)) return false;
  const rel = pathname === '/' ? 'index.html' : pathname.replace(/^\/+/, '');
  let target = path.resolve(distDir, rel);
  if (!target.startsWith(distDir) || !fs.existsSync(target) || fs.statSync(target).isDirectory()) {
    target = path.join(distDir, 'index.html');
  }
  if (!fs.existsSync(target)) return false;
  const ext = path.extname(target).toLowerCase();
  res.writeHead(200, { 'Content-Type': MIME_TYPES[ext] || 'application/octet-stream' });
  fs.createReadStream(target).pipe(res);
  return true;
}

const server = http.createServer(async (req, res) => {
  if (req.method === 'OPTIONS') {
    res.writeHead(204, {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Headers': 'Authorization, Content-Type',
      'Access-Control-Allow-Methods': 'GET, POST, DELETE, OPTIONS',
    });
    res.end();
    return;
  }

  const reqUrl = new URL(req.url || '/', `http://${req.headers.host || 'localhost'}`);
  const { pathname, searchParams } = reqUrl;

  if (!pathname.startsWith('/api/')) {
    if (serveStaticDist(req, res, pathname)) return;
    sendJson(res, 200, {
      service: 'Jarvis Pocket Windows Agent',
      hint: 'Corré npm run build para servir la PWA directo desde acá, o conectate desde tu PWA en la nube.',
    });
    return;
  }

  if (pathname === '/api/ping' && req.method === 'GET') {
    sendJson(res, 200, { ok: true, service: 'jarvis-agent', version: '1.0.0' });
    return;
  }

  if (!isAuthorized(req)) {
    sendJson(res, 401, { ok: false, error: 'Token inválido o faltante (Authorization: Bearer ...)' });
    return;
  }

  try {
    if (pathname === '/api/health' && req.method === 'GET') {
      const [disks, hasYtDlp, hasFfmpeg] = await Promise.all([
        getDiskInfo(),
        checkBinary('yt-dlp'),
        checkBinary('ffmpeg'),
      ]);
      const cpus = os.cpus();
      sendJson(res, 200, {
        ok: true,
        hostname: os.hostname(),
        platform: process.platform,
        uptimeSec: Math.floor(os.uptime()),
        cpuModel: cpus[0]?.model || 'CPU',
        cpuCores: cpus.length,
        ramTotalBytes: os.totalmem(),
        ramFreeBytes: os.freemem(),
        disks,
        tools: { ytDlp: hasYtDlp, ffmpeg: hasFfmpeg, cobaltConfigured: Boolean(config.cobaltApiUrl) },
        folders: { drop: config.dropDir, downloads: config.downloadsDir },
      });
      return;
    }

    if (pathname === '/api/screenshot' && req.method === 'GET') {
      const png = await captureScreenshot();
      res.writeHead(200, {
        'Content-Type': 'image/png',
        'Cache-Control': 'no-store',
        'Access-Control-Allow-Origin': '*',
      });
      res.end(png);
      return;
    }

    if (pathname === '/api/processes' && req.method === 'GET') {
      const ps =
        'Get-Process | Where-Object { $_.WorkingSet64 -gt 20MB } | Sort-Object WorkingSet64 -Descending | Select-Object -First 25 Id,ProcessName,MainWindowTitle,WorkingSet64 | ConvertTo-Json -Compress';
      const out = await runExecFile('powershell.exe', ['-NoProfile', '-Command', ps], 8000);
      let items = [];
      if (out.ok && out.stdout) {
        const parsed = JSON.parse(out.stdout);
        items = (Array.isArray(parsed) ? parsed : [parsed]).map((p) => ({
          pid: p.Id,
          name: p.ProcessName,
          title: p.MainWindowTitle || '',
          memoryBytes: Number(p.WorkingSet64) || 0,
        }));
      }
      sendJson(res, 200, { ok: true, processes: items });
      return;
    }

    if (pathname === '/api/processes/kill' && req.method === 'POST') {
      const body = await readJsonBody(req);
      const pid = Number(body.pid);
      if (!body.approved || !Number.isInteger(pid) || pid <= 4) {
        sendJson(res, 400, { ok: false, error: 'Requiere aprobación explícita y PID válido (>4).' });
        return;
      }
      const out = await runExecFile('taskkill', ['/PID', String(pid), '/F'], 5000);
      sendJson(res, out.ok ? 200 : 500, { ok: out.ok, output: out.stdout || out.stderr });
      return;
    }

    if (pathname === '/api/apps/launch' && req.method === 'POST') {
      const body = await readJsonBody(req);
      const target = SAFE_APPS[String(body.app || '').toLowerCase()];
      if (!target) {
        sendJson(res, 400, { ok: false, error: 'App no permitida en la lista segura.' });
        return;
      }
      spawn('cmd.exe', ['/c', 'start', '', target], { detached: true, stdio: 'ignore', windowsHide: true }).unref();
      sendJson(res, 200, { ok: true, launched: target });
      return;
    }

    if (pathname === '/api/power' && req.method === 'POST') {
      const body = await readJsonBody(req);
      if (!body.approved) {
        sendJson(res, 400, { ok: false, error: 'Acción de energía requiere aprobación explícita.' });
        return;
      }
      if (body.action === 'abort') {
        const out = await runExecFile('shutdown', ['/a'], 5000);
        sendJson(res, 200, { ok: out.ok, message: out.ok ? 'Apagado cancelado.' : out.stderr });
        return;
      }
      if (body.action === 'lock') {
        const out = await runExecFile('rundll32.exe', ['user32.dll,LockWorkStation'], 5000);
        sendJson(res, out.ok ? 200 : 500, { ok: out.ok, message: out.ok ? 'Pantalla bloqueada.' : out.stderr });
        return;
      }
      if (body.action === 'sleep') {
        sendJson(res, 200, { ok: true, message: 'Suspendiendo PC...' });
        setTimeout(() => {
          void runExecFile(
            'powershell.exe',
            [
              '-NoProfile',
              '-Command',
              "Add-Type -AssemblyName System.Windows.Forms; [System.Windows.Forms.Application]::SetSuspendState('Suspend', $false, $false)",
            ],
            8000,
          );
        }, 400);
        return;
      }
      const minutes = Math.min(480, Math.max(1, Math.round(Number(body.minutes) || 15)));
      const flag = body.action === 'restart' ? '/r' : '/s';
      const out = await runExecFile('shutdown', [flag, '/t', String(minutes * 60)], 5000);
      sendJson(res, out.ok ? 200 : 500, {
        ok: out.ok,
        message: out.ok ? `${body.action === 'restart' ? 'Reinicio' : 'Apagado'} programado en ${minutes} min.` : out.stderr,
      });
      return;
    }

    if (pathname === '/api/media' && req.method === 'POST') {
      const body = await readJsonBody(req);
      const MEDIA_VK = {
        mute: 0xad,
        vol_down: 0xae,
        vol_up: 0xaf,
        next: 0xb0,
        prev: 0xb1,
        play_pause: 0xb3,
      };
      const action = String(body.action || '');
      const vk = MEDIA_VK[action];
      if (!vk) {
        sendJson(res, 400, { ok: false, error: 'Acción multimedia inválida.' });
        return;
      }
      const repeats = action === 'vol_up' || action === 'vol_down' ? 2 : 1;
      const ps = `
Add-Type -TypeDefinition 'using System.Runtime.InteropServices; public class Kbd { [DllImport("user32.dll")] public static extern void keybd_event(byte bVk, byte bScan, uint dwFlags, int dwExtraInfo); }'
for ($i = 0; $i -lt ${repeats}; $i++) { [Kbd]::keybd_event(${vk}, 0, 0, 0); [Kbd]::keybd_event(${vk}, 0, 2, 0) }
`;
      const out = await runExecFile('powershell.exe', ['-NoProfile', '-Command', ps], 6000);
      sendJson(res, out.ok ? 200 : 500, { ok: out.ok, action, error: out.ok ? undefined : out.stderr });
      return;
    }

    if (pathname === '/api/url/open' && req.method === 'POST') {
      const body = await readJsonBody(req);
      const targetUrl = String(body.url || '').trim();
      if (!isValidHttpUrl(targetUrl)) {
        sendJson(res, 400, { ok: false, error: 'URL inválida (debe iniciar con http:// o https://).' });
        return;
      }
      spawn('rundll32.exe', ['url.dll,FileProtocolHandler', targetUrl], {
        detached: true,
        stdio: 'ignore',
        windowsHide: true,
      }).unref();
      sendJson(res, 200, { ok: true, url: targetUrl });
      return;
    }

    if (pathname === '/api/notes/sync' && req.method === 'POST') {
      const body = await readJsonBody(req);
      const incoming = Array.isArray(body.notes) ? body.notes : [];
      const notesFile = path.join(config.dropDir, 'jarvis-notas.md');
      const existing = fs.existsSync(notesFile) ? fs.readFileSync(notesFile, 'utf-8') : '# Notas de Jarvis Pocket\n';
      let appended = '';
      const syncedIds = [];
      for (const n of incoming.slice(0, 100)) {
        const id = String(n?.id || '').replace(/[^a-zA-Z0-9_-]/g, '');
        const text = String(n?.text || '').trim().slice(0, 4000);
        if (!id || !text) continue;
        syncedIds.push(id);
        if (existing.includes(`<!-- id:${id} -->`)) continue;
        const when = String(n?.createdAt || new Date().toISOString()).slice(0, 19).replace('T', ' ');
        appended += `\n## ${when} <!-- id:${id} -->\n${text}\n`;
      }
      if (appended || !fs.existsSync(notesFile)) {
        fs.writeFileSync(notesFile, existing + appended, 'utf-8');
      }
      sendJson(res, 200, { ok: true, syncedIds, file: 'jarvis-notas.md', count: syncedIds.length });
      return;
    }

    if (pathname === '/api/files' && req.method === 'GET') {
      const rootDir = getRootDir(searchParams.get('dir'));
      const query = (searchParams.get('q') || '').toLowerCase();
      const entries = fs.readdirSync(rootDir, { withFileTypes: true });
      const files = entries
        .filter((e) => e.isFile() && (!query || e.name.toLowerCase().includes(query)))
        .map((e) => {
          const stat = fs.statSync(path.join(rootDir, e.name));
          return {
            name: e.name,
            sizeBytes: stat.size,
            modifiedAt: stat.mtime.toISOString(),
          };
        })
        .sort((a, b) => new Date(b.modifiedAt).getTime() - new Date(a.modifiedAt).getTime());
      sendJson(res, 200, { ok: true, dir: rootDir, files });
      return;
    }

    if (pathname === '/api/files/upload' && req.method === 'POST') {
      const rootDir = getRootDir(searchParams.get('dir'));
      const resolved = safeResolveFile(rootDir, searchParams.get('name'));
      if (!resolved) {
        sendJson(res, 400, { ok: false, error: 'Nombre de archivo inválido.' });
        return;
      }
      let received = 0;
      const ws = fs.createWriteStream(resolved.full);
      req.on('data', (chunk) => {
        received += chunk.length;
        if (received > MAX_UPLOAD_BYTES) {
          ws.destroy();
          fs.rmSync(resolved.full, { force: true });
          req.destroy();
        }
      });
      req.pipe(ws);
      ws.on('finish', () => {
        sendJson(res, 200, { ok: true, name: resolved.cleanName, sizeBytes: received });
      });
      ws.on('error', (err) => {
        sendJson(res, 500, { ok: false, error: err.message });
      });
      return;
    }

    if (pathname === '/api/files/download' && req.method === 'GET') {
      const rootDir = getRootDir(searchParams.get('dir'));
      const resolved = safeResolveFile(rootDir, searchParams.get('name'));
      if (!resolved || !fs.existsSync(resolved.full)) {
        sendJson(res, 404, { ok: false, error: 'Archivo no encontrado.' });
        return;
      }
      const stat = fs.statSync(resolved.full);
      res.writeHead(200, {
        'Content-Type': 'application/octet-stream',
        'Content-Length': stat.size,
        'Content-Disposition': `attachment; filename="${encodeURIComponent(resolved.cleanName)}"`,
        'Access-Control-Allow-Origin': '*',
      });
      fs.createReadStream(resolved.full).pipe(res);
      return;
    }

    if (pathname === '/api/files/largest' && req.method === 'GET') {
      const target =
        searchParams.get('scope') === 'user_downloads'
          ? path.join(os.homedir(), 'Downloads')
          : getRootDir(searchParams.get('dir'));
      const ps = `Get-ChildItem -Path '${target.replace(/'/g, "''")}' -File -Recurse -ErrorAction SilentlyContinue | Sort-Object Length -Descending | Select-Object -First 15 FullName,Name,Length | ConvertTo-Json -Compress`;
      const out = await runExecFile('powershell.exe', ['-NoProfile', '-Command', ps], 15000);
      let items = [];
      if (out.ok && out.stdout) {
        const parsed = JSON.parse(out.stdout);
        items = (Array.isArray(parsed) ? parsed : [parsed]).map((f) => ({
          name: f.Name,
          path: f.FullName,
          sizeBytes: Number(f.Length) || 0,
        }));
      }
      sendJson(res, 200, { ok: true, scope: target, files: items });
      return;
    }

    if (pathname === '/api/download' && req.method === 'POST') {
      const body = await readJsonBody(req);
      if (!isValidHttpUrl(body.url)) {
        sendJson(res, 400, { ok: false, error: 'URL inválida (debe iniciar con http:// o https://).' });
        return;
      }
      const job = startDownloadJob(body);
      sendJson(res, 202, { ok: true, job });
      return;
    }

    if (pathname === '/api/download/jobs' && req.method === 'GET') {
      sendJson(res, 200, { ok: true, jobs: downloadJobs });
      return;
    }

    if (pathname === '/api/script/execute' && req.method === 'POST') {
      const body = await readJsonBody(req);
      const command = String(body.command || '').trim();
      if (!body.approved || !command) {
        sendJson(res, 400, { ok: false, error: 'Ejecución rechazada: requiere aprobación humana ("TU SÍ") y comando.' });
        return;
      }
      const out = await runExecFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', command], 20000);
      sendJson(res, 200, out);
      return;
    }

    sendJson(res, 404, { ok: false, error: 'Endpoint no encontrado.' });
  } catch (err) {
    sendJson(res, 500, { ok: false, error: err instanceof Error ? err.message : 'Error interno' });
  }
});

function getLanAddresses() {
  const nets = os.networkInterfaces();
  const addrs = [];
  for (const list of Object.values(nets)) {
    for (const net of list || []) {
      if (net.family === 'IPv4' && !net.internal) addrs.push(net.address);
    }
  }
  return addrs;
}

