// --- Minimal .env loader & auto-token bootstrap ---
function loadEnv() {
  const env = {};
  if (fs.existsSync(ENV_PATH)) {
    const raw = fs.readFileSync(ENV_PATH, 'utf-8');
    for (const line of raw.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq === -1) continue;
      const k = trimmed.slice(0, eq).trim();
      const v = trimmed.slice(eq + 1).trim();
      env[k] = v;
    }
  }
  if (!env.JARVIS_TOKEN && !process.env.JARVIS_TOKEN) {
    const generated = crypto.randomBytes(24).toString('hex');
    env.JARVIS_TOKEN = generated;
    const prefix = fs.existsSync(ENV_PATH) ? '\n' : '# Auto-generated by Jarvis Pocket Agent\n';
    fs.appendFileSync(ENV_PATH, `${prefix}JARVIS_TOKEN=${generated}\n`, 'utf-8');
  }
  return {
    port: Number(process.env.JARVIS_PORT || env.JARVIS_PORT || 8787),
    token: process.env.JARVIS_TOKEN || env.JARVIS_TOKEN,
    dropDir: process.env.JARVIS_DROP_DIR || env.JARVIS_DROP_DIR || path.join(os.homedir(), 'JarvisDrop'),
    downloadsDir:
      process.env.JARVIS_DOWNLOADS_DIR || env.JARVIS_DOWNLOADS_DIR || path.join(os.homedir(), 'JarvisDownloads'),
    cobaltApiUrl: process.env.COBALT_API_URL || env.COBALT_API_URL || '',
  };
}

